// ردود ثابتة (مو عشوائية) لكلمتين محددتين طلبهم المستخدم بالضبط
const BARB_REPLY = 'تيت، لا تطول علينا 😅';
const BAK_REPLY = 'ولكم باك، أحلى مين ينور؟ 😏';

function pickRandom(list) {
  return list[Math.floor(Math.random() * list.length)];
}

// ============ تحديد نوع التحية من نص الرسالة ============
function getReply(body) {
  if (!body) return null;
  const text = body.trim();
  const lower = text.toLowerCase();

  // "سلام عليكم" substring بيطابق "سلام عليكم" و"السلام عليكم" مع بعض
  if (text.includes('سلام عليكم')) return pickRandom(SALAM_REPLIES);

  // "صباح الخير" / "صباحو" (دارجة ليبية شائعة) / "صباح النور"
  if (text.includes('صباح الخير') || text.includes('صباحو') || text.includes('صباح النور')) {
    return pickRandom(SABAH_REPLIES);
  }

  // أي كلمة فيها "تصبحو" (تصبحون على خير، تصبحوا على خير...)
  if (text.includes('تصبحو')) return pickRandom(TESBAHO_REPLIES);

  // "برب" (BRB) - رد ثابت محدد
  if (text.includes('برب')) return BARB_REPLY;

  // "باك" - رد ثابت محدد (كلمة لحالها، مختلفة عن "باي")
  if (text.includes('باك')) return BAK_REPLY;

  // وداع عام: باي / مع السلامة - عربي أو إنجليزي
  if (
    text.includes('باي') ||
    text.includes('مع السلامة') ||
    lower.includes('bye')
  ) {
    return pickRandom(BYE_REPLIES);
  }

  return null;
}

module.exports = { getReply };
