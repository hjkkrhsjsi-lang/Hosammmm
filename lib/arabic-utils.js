// توحيد النص العربي قبل المقارنة، عشان الجواب الصح ينقبل
// حتى لو مكتوب بشكل مختلف شوي أو فيه رموز مخفية من واتساب.

function normalizeArabicText(text) {
  if (!text) return '';
  return text
    // إزالة رموز اتجاه النص المخفية اللي واتساب ممكن يضيفها (RTL/LRM/ZWJ...)
    .replace(/[\u200B-\u200F\u202A-\u202E\uFEFF]/g, '')
    .trim()
    .toLowerCase()
    // إزالة التشكيل (فتحة، ضمة، كسرة، شدة، سكون...)
    .replace(/[\u064B-\u065F\u0670]/g, '')
    // توحيد أشكال الألف (أ إ آ) لألف عادية
    .replace(/[إأآ]/g, 'ا')
    // توحيد التاء المربوطة مع الهاء (قهوة = قهوه)
    .replace(/ة/g, 'ه')
    // توحيد الألف المقصورة مع الياء (على = علي)
    .replace(/ى/g, 'ي')
    // توحيد المسافات المتكررة لمسافة وحدة
    .replace(/\s+/g, ' ')
    .trim();
}

module.exports = { normalizeArabicText };
